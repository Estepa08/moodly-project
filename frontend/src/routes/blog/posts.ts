export const getPostBySlug = (slug: string): Post | undefined => POSTS.find((p) => p.slug === slug);

export const getPostsByCategory = (category: CategorySlug): Post[] =>
  POSTS.filter((p) => p.category === category);

export const getRelatedPosts = (post: Post, limit = 2): Post[] =>
  getPostsByCategory(post.category)
    .filter((p) => p.slug !== post.slug)
    .slice(0, limit);

export const getCategoryName = (category: CategorySlug): string => CATEGORIES[category].name;

export function formatDate(iso: string): string {
  const d = new Date(`${iso}T00:00:00`);
  return d.toLocaleDateString('ru-RU', { year: 'numeric', month: 'long', day: 'numeric' });
}
